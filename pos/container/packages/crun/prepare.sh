# autoreconf generates the build system, crun's and its libocispec
# submodule's. Not autogen.sh: it updates the submodules with git, and the
# synced tree has them already. The version is a snapshot name
# (git-version-gen reads .tarball-version). git-version.h, which crun
# includes for `crun --version`, comes from .tarball-git-version.h where
# there is no .git, as in crun's release tarballs: the upstream commit.

prep() {
  prep_version
  printf '/* autogenerated.  */\n#ifndef GIT_VERSION\n# define GIT_VERSION "%s"\n#endif\n' \
    "$(prep_upstream commit)" > .tarball-git-version.h
  autoreconf -fi
}
